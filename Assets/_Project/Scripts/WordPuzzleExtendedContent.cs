        public static PuzzleLevel[] Create() {
            string[] rows = Data.Split(new[] { '\r', '\n' }, StringSplitOptions.RemoveEmptyEntries);
            var levels = new PuzzleLevel[rows.Length];
            for (int i = 0; i < rows.Length; i++) {
                string[] fields = rows[i].Split('|');
                if (fields.Length != 4) throw new FormatException("Invalid extended puzzle row " + i);
                string answer = fields[0];
                var tiles = new string[answer.Length];
                for (int j = 0; j < answer.Length; j++) tiles[j] = answer[j].ToString();
                levels[i] = new PuzzleLevel {
                    Id = 21 + i, Answer = answer, Clue = fields[1], Topic = fields[2],
                    Difficulty = int.Parse(fields[3]), Letters = tiles
                };
            }
            return levels;
